#!/usr/bin/env python3
"""Rasterize compact tint masks and generate their shared C layout constants."""
import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    out = ROOT / 'assets/generated'
    out.mkdir(exist_ok=True)
    layout = json.loads((ROOT / 'assets/printer-spools.json').read_text())
    # Neutralize the static colour fringe beneath the tint masks. Processing
    # happens once at build time; no bitmap is regenerated for a slot edit.
    sys.path.insert(0, str(ROOT / 'backend'))
    from storage import prepare_image
    with tempfile.TemporaryDirectory(prefix='spool-base-') as directory:
        base = prepare_image(ROOT / 'assets/printer-with-cfs.png', directory,
                             'printer', (400, 286), lighten=True)
        x, y, width, height = layout['neutral_region']
        region = '%dx%d+%d+%d' % (width, height, x, y)
        subprocess.run(['convert', base, '-region', region, '-modulate', '100,0,100',
                        '+region', 'PNG32:'+str(out/'printer-with-cfs-base.png')],
                       check=True, capture_output=True)
    entries = []
    for layer in layout['spools']:
        name = layer['name']
        subprocess.run(['convert', '-background', 'none', str(ROOT / 'assets' / (name+'.svg')),
                        'PNG32:'+str(out / (name+'.png'))], check=True, capture_output=True)
        entries.append('    {"%s.png", %d, %d},' % (name, layer['x'], layer['y']))
    (out / 'printer_spool_layout.h').write_text(
        '/* Generated by build_printer_layers.py from assets/printer-spools.json. */\n'
        'static const struct { const char *file; int x, y; } spool_layers[4] = {\n'
        + '\n'.join(entries) + '\n};\n')


if __name__ == '__main__':
    build()

def apply(text):
    for desc, old, new in CHANGES:
        n = text.count(old)
        if n != 1:
            sys.exit("make_k2plus_cfg: '%s' matched %d times (want 1). The K2 "
                     "config changed: update the script." % (desc, n))
        text = text.replace(old, new)
    for desc, old, new, want in CHANGES_ALL:
        n = text.count(old)
        if n != want:
            sys.exit("make_k2plus_cfg: '%s' matched %d times (want %d)"
                     % (desc, n, want))
        out = []
        for line in text.split('\n'):
            if old in line:
                indent = line[:len(line) - len(line.lstrip())]
                line = line.replace(old, new.replace('{indent}', indent))
            out.append(line)
        text = '\n'.join(out)
    # The first line of the K2 file names the K2: replace it
    first, rest = text.split('\n', 1)
    if not first.startswith('# Creality K2 / F021'):
        sys.exit("make_k2plus_cfg: unexpected first line %r" % first)
    return HEADER + rest.rstrip('\n') + '\n' + EXTRA



def main():
    with open(SRC, encoding='utf-8', newline='') as f:
        text = f.read()
    if '\r' in text:
        sys.exit("make_k2plus_cfg: %s has CR line endings" % SRC)
    out = apply(text)
    check = ('position_max: 262', 'gear_ratio', 'tmc2208 stepper_z',
             'Y261', 'X205', 'Y265.5', 'X130 Y125')
    left = [c for c in check if c in out]
    if left:
        sys.exit("make_k2plus_cfg: K2 values left in the output: %s" % left)
    with open(DST, 'w', encoding='utf-8', newline='\n') as f:
        f.write(out)
    print("wrote %s (%d changes)" % (os.path.relpath(DST, ROOT),
                                     len(CHANGES) + len(CHANGES_ALL)))


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
# Printed pressure-advance check for the K2: a row of nested chevrons, each
# printed at its own pressure advance and labelled with it (x1000), after
# Andrew Ellis' PA pattern (OrcaSlicer "PA Pattern"). Shows whether the
# strain-gauge value (PA_CAL_STATIC / auto PA) is right in a real print.
#
#   python3 pa_pattern.py --slot C [--start 0.02 --step 0.006 --count 11]
#
# Defaults centre the range on the slot's saved pressure advance. Look at the
# chevron tips: too little PA bulges at the corner and thins after it, too
# much leaves a gap or rounded corner. Pick the sharpest, even-width tip and
# compare it with the slot's value; save another with
#   CFS_SLOT_SET SLOT=C PA=0.05
#
# This file may be distributed under the terms of the GNU GPLv3 license.
import argparse, json, math, urllib.request

SLOTS = "ABCD"
FIL_AREA = math.pi * (1.75 / 2.) ** 2
W = 0.45
H = 0.2
LAYERS = 4
WALLS = 3
LEG = 30.
PITCH = 10.
CENTRE_Y = 130.
RETRACT = 1.0
DW, DH = 2.4, 4.2
SEG = {'a': ((0, DH), (DW, DH)), 'b': ((DW, DH), (DW, DH / 2)),
       'c': ((DW, DH / 2), (DW, 0)), 'd': ((DW, 0), (0, 0)),
       'e': ((0, 0), (0, DH / 2)), 'f': ((0, DH / 2), (0, DH)),
       'g': ((0, DH / 2), (DW, DH / 2))}
DIGITS = {'0': 'abcdef', '1': 'bc', '2': 'abged', '3': 'abgcd', '4': 'fgbc',
          '5': 'afgcd', '6': 'afgedc', '7': 'abc', '8': 'abcdefg',
          '9': 'gfabcd'}


def area(w, h):
    return (w - h) * h + math.pi * (h / 2.) ** 2


class Gcode:
    def __init__(self):
        self.out, self.pos, self.z = [], None, 0.

    def emit(self, line):
        self.out.append(line)

    def travel(self, x, y):
        if self.pos and math.hypot(x - self.pos[0], y - self.pos[1]) < 0.01:
            return
        far = self.pos is None or math.hypot(x - self.pos[0],
                                             y - self.pos[1]) > 2.
        if far:
            self.emit("G1 E-%.2f F2400" % RETRACT)
            self.emit("G1 Z%.3f F600" % (self.z + 0.4))
        self.emit("G1 X%.3f Y%.3f F18000" % (x, y))
        if far:
            self.emit("G1 Z%.3f F600" % self.z)
            self.emit("G1 E%.2f F2400" % RETRACT)
        self.pos = (x, y)

    def line(self, x, y, e_per_mm, speed):
        d = math.hypot(x - self.pos[0], y - self.pos[1])
        self.emit("G1 X%.3f Y%.3f E%.5f F%d" % (x, y, d * e_per_mm,
                                                 speed * 60))
        self.pos = (x, y)


def slot_record(slot):
    try:
        url = ("http://192.168.3.64:7126/server/files/config/"
               "hark_cfs_slots.json")
        return json.load(urllib.request.urlopen(url, timeout=5))[
            'slots'][slot]
    except Exception:
        return {}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--slot', default='C')
    ap.add_argument('--start', type=float)
    ap.add_argument('--step', type=float, default=0.006)
    ap.add_argument('--count', type=int, default=11)
    ap.add_argument('--speed', type=float, default=120.)
    ap.add_argument('--accel', type=int, default=5000)
    ap.add_argument('-o')
    a = ap.parse_args()
    slot = a.slot.upper()
    rec = slot_record(slot)
    temp = rec.get('nozzle_temp') or 220
    bed = rec.get('bed_temp') or 55
    centre = rec.get('pressure_advance') or 0.05
    start = a.start if a.start is not None else max(
        0., round(centre - a.step * (a.count // 2), 3))
    pas = [round(start + i * a.step, 4) for i in range(a.count)]
    dx = LEG * math.cos(math.radians(45))
    dy = LEG * math.sin(math.radians(45))
    x0 = 130. - (PITCH * (a.count - 1) + dx) / 2.
    sp = W - H * (1. - math.pi / 4.)
    e_mm = area(W, H) / FIL_AREA * (rec.get('flow_ratio') or 1.)

    g = Gcode()
    g.emit("; K2 pressure advance pattern (Hark Tech), generated by"
           " pa_pattern.py")
    g.emit("; slot %s %dC bed %dC, PA %s (left to right, label = PA x1000)"
           % (slot, temp, bed, ", ".join("%.3f" % p for p in pas)))
    xs = [x0 + i * PITCH for i in range(a.count)]
    g.emit("EXCLUDE_OBJECT_DEFINE NAME=pa_pattern CENTER=130,%.1f "
           "POLYGON=[[%.1f,%.1f],[%.1f,%.1f],[%.1f,%.1f],[%.1f,%.1f]]"
           % (CENTRE_Y, xs[0] - 2, CENTRE_Y - dy - 8, xs[-1] + dx + 4,
              CENTRE_Y - dy - 8, xs[-1] + dx + 4, CENTRE_Y + dy + 2,
              xs[0] - 2, CENTRE_Y + dy + 2))
    g.emit("M106 S0")
    g.emit("START_PRINT EXTRUDER_TEMP=%d BED_TEMP=%d TOOL=%d"
           % (temp, bed, SLOTS.index(slot)))
    g.emit("T%d" % SLOTS.index(slot))
    g.emit("M83\nG90\nG1 Z0.6 F600\nM104 S%d\nG92 E0" % temp)
    g.emit("EXCLUDE_OBJECT_START NAME=pa_pattern")
    for layer in range(LAYERS):
        g.z = H * (layer + 1)
        g.emit(";LAYER:%d" % layer)
        if layer == 1:
            g.emit("M106 S255")
        speed = 30. if layer == 0 else a.speed
        g.emit("SET_VELOCITY_LIMIT ACCEL=%d"
               % (1000 if layer == 0 else a.accel))
        g.emit("G1 Z%.3f F600" % g.z)
        for x, pa in zip(xs, pas):
            g.emit("SET_PRESSURE_ADVANCE ADVANCE=%.4f" % pa)
            for k in range(WALLS):
                # Each wall is the chevron shifted right by one line spacing
                # measured across the 45 degree legs
                off = k * sp / math.sin(math.radians(45))
                g.travel(x + off + dx, CENTRE_Y + dy)
                g.line(x + off, CENTRE_Y, e_mm, speed)
                g.line(x + off + dx, CENTRE_Y - dy, e_mm, speed)
        if layer < 2:
            # Labels under the bottom leg ends, in the first two layers so
            # no travel crosses the finished part
            g.emit("SET_PRESSURE_ADVANCE ADVANCE=%.4f" % centre)
            for x, pa in zip(xs, pas):
                text = "%d" % round(pa * 1000)
                lx = x + dx - len(text) * (DW + 0.9) / 2. + 2.
                ly = CENTRE_Y - dy - 7.
                for ch in text:
                    for s in DIGITS[ch]:
                        (ax, ay), (bx, by) = SEG[s]
                        g.travel(lx + ax, ly + ay)
                        g.line(lx + bx, ly + by, area(0.4, H) / FIL_AREA,
                               20)
                    lx += DW + 0.9
    g.emit("EXCLUDE_OBJECT_END NAME=pa_pattern")
    g.emit("G1 E-%.2f F2400\nG1 Z10 F600\nEND_PRINT" % RETRACT)
    out = a.o or "K2_pa_pattern_slot%s_%03d-%03d.gcode" % (
        slot, round(pas[0] * 1000), round(pas[-1] * 1000))
    with open(out, 'w') as f:
        f.write("\n".join(g.out) + "\n")
    print("wrote %s: slot %s %dC, PA %s" % (
        out, slot, temp, " ".join("%.3f" % p for p in pas)))


if __name__ == '__main__':
    main()
